const f = (key: string, label: string, kind: OpsField["kind"], extra: Partial<OpsField> = {}): OpsField => ({ key, label, kind, ...extra });
const sel = (key: string, label: string, options: string[], extra: Partial<OpsField> = {}): OpsField => ({ key, label, kind: "select", options, required: true, dflt: options[0], ...extra });
const ro = (key: string, label: string, kind: OpsField["kind"] = "text"): OpsField => ({ key, label, kind, readOnly: true });
const act = (key: string, label: string, set: OpsAction["set"], when: OpsAction["when"], tone?: OpsAction["tone"]): OpsAction => ({ key, label, set, when, ...(tone ? { tone } : {}) });

